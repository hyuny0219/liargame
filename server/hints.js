function randOf(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

// 시민/스파이 봇의 설명 한 마디
function citizenLine(word) {
  const hint = HINTS[word];
  if (hint) return Array.isArray(hint) ? randOf(hint) : hint;
  return randOf(CITIZEN_GENERIC);
}

